// Builds supabase/schema.sql (Postgres) from the SQLite migrations, so one schema history serves D1, node:sqlite and Supabase.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
const dir = new URL('../migrations/', import.meta.url);
const files = readdirSync(dir).filter(f => f.endsWith('.sql')).sort();
const head = readFileSync(new URL('../supabase/functions.sql', import.meta.url), 'utf8');
const toPg = (s) => s
  .replace(/INTEGER PRIMARY KEY AUTOINCREMENT/g, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
  .replace(/INSERT OR IGNORE INTO ([\s\S]*?);/g, (_, body) => `INSERT INTO ${body} ON CONFLICT DO NOTHING;`)
  .replace(/ALTER TABLE (\w+) ADD COLUMN /g, 'ALTER TABLE $1 ADD COLUMN IF NOT EXISTS ');
let out = `-- GENERATED by scripts/pg-schema.mjs from migrations/*.sql. Do not edit by hand.\n${head}\n`;
const SEQ = `
DO $$ DECLARE r record; BEGIN -- identity columns continue after explicitly inserted ids
  FOR r IN SELECT table_name FROM information_schema.columns WHERE table_schema='public' AND column_name='id' AND is_identity='YES' LOOP
    EXECUTE format('SELECT setval(pg_get_serial_sequence(%L,''id''), COALESCE((SELECT MAX(id) FROM %I),0)+1, false)', r.table_name, r.table_name);
  END LOOP; END $$;`;
for (const f of files) out += `\n-- ── ${f} ──\n${toPg(readFileSync(new URL(f, dir), 'utf8'))}\n${SEQ}\n`;
out += `
-- the app only talks to the database through pf_exec / pf_batch; lock tables away from the public API
DO $$ DECLARE t record; BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname='public' LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t.tablename);
  END LOOP; END $$;
`;
writeFileSync(new URL('../supabase/schema.sql', import.meta.url), out);
console.log('wrote supabase/schema.sql', out.length);
